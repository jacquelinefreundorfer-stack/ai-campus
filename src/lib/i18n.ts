// ── i18n: path-prefix-based internationalization ──────────────────────────────
// Locales: en (default, /), de (/de/...), es (/es/...)

export type Locale = "en" | "de" | "es";

export const defaultLocale: Locale = "en";

export const supportedLocales: Locale[] = ["en", "de", "es"];

// Detect locale from URL pathname
export function detectLocale(pathname: string): Locale {
  const seg = pathname.split("/")[1];
  if (seg === "de" || seg === "es") return seg;
  return "en";
}

// Get the path prefix for a locale (empty for default)
export function localePrefix(locale: Locale): string {
  return locale === "en" ? "" : `/${locale}`;
}

// Build a localized href
export function localizedHref(locale: Locale, path: string): string {
  // Remove any existing locale prefix from path
  const clean = path.replace(/^\/(de|es)(\/|$)/, "/").replace(/\/$/, "") || "/";
  if (locale === "en") return clean;
  return `/${locale}${clean === "/" ? "" : clean}`;
}

// Get the equivalent path in another locale from the current URL
export function switchLocalePath(currentPath: string, targetLocale: Locale): string {
  const clean = currentPath.replace(/^\/(de|es)(\/|$)/, "/").replace(/\/$/, "") || "/";
  if (targetLocale === "en") return clean;
  return `/${targetLocale}${clean === "/" ? "" : clean}`;
}

// ── Translation lookup ─────────────────────────────────────────────────────────

export function t(locale: Locale, key: string): string {
  const keys = key.split(".");
  let node: any = translations[locale];
  for (const k of keys) {
    if (node == null) break;
    node = node[k];
  }
  if (typeof node === "string") return node;
  // Fallback to English
  let fallback: any = translations["en"];
  for (const k of keys) {
    if (fallback == null) break;
    fallback = fallback[k];
  }
  if (typeof fallback === "string") return fallback;
  return key; // Last resort
}

